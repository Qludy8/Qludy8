// Armes dessinées pièce par pièce, proportions inspirées d'armes réelles (noms 100 % inventés).
// Espace 1000 × 360, canon vers la droite. Matériaux :
//   paint  : pièce peinte par le skin          poly  : polymère / bakélite      metal : acier bruni
//   metal2 : acier bruni posé par-dessus      steel : acier poli (biseaux)     wood  : bois
//   brass  : laiton    rubber : caoutchouc    glass : optique                  hole  : évidement
//   wire   : pièce filaire (pontet)           tex   : zone striée/quadrillée   line / hi : gravures et reflets
const P = (k, d) => ({ k, d });
const R = (x, y, w, h) => `M${x} ${y}h${w}v${h}h${-w}Z`;
const C = (cx, cy, r) => `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`;
const RR = (x, y, w, h, r) => `M${x + r} ${y}h${w - 2 * r}q${r} 0 ${r} ${r}v${h - 2 * r}q0 ${r} ${-r} ${r}h${-(w - 2 * r)}q${-r} 0 ${-r} ${-r}v${-(h - 2 * r)}q0 ${-r} ${r} ${-r}Z`;
const rep = (n, f) => Array.from({ length: n }, (_, i) => f(i)).join(' ');
const rail = (x, y, len, h = 9) => R(x, y, len, h) + ' ' + rep(Math.floor(len / 13), (i) => R(x + 3 + i * 13, y - 5, 8, 5));
const vl = (x, y1, y2, n, s) => rep(n, (i) => `M${x + i * s} ${y1}V${y2}`);
const hl = (x1, x2, y, n, s) => rep(n, (i) => `M${x1} ${y + i * s}H${x2}`);
const screws = (pts, r = 4.5) => pts.map(([x, y]) => C(x, y, r)).join(' ');
const slots = (pts, r = 0.8) => pts.map(([x, y]) => `M${x - 3 * r} ${y}h${6 * r}`).join(' ');

