// Boîte englobante de chaque modèle (points absolus des chemins) → cadrage automatique sur la carte
function bbox(parts) {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const { d } of parts) {
    const re = /([MLQCT])([^A-Za-z]*)/g; let m;
    while ((m = re.exec(d))) {
      const n = m[2].trim().split(/[\s,]+/).filter(Boolean).map(Number);
      for (let i = 0; i + 1 < n.length; i += 2) {
        x0 = Math.min(x0, n[i]); x1 = Math.max(x1, n[i]); y0 = Math.min(y0, n[i + 1]); y1 = Math.max(y1, n[i + 1]);
      }
    }
  }
  return { x: x0, y: y0, w: x1 - x0, h: y1 - y0 };
}
