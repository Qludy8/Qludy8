// Boîte englobante d'un ensemble de chemins (M L H V Q C Z en absolu ou relatif, arcs approximés)
export function pathsBox(ds) {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  const add = (x, y) => { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); };
  for (const d of ds) {
    const toks = d.match(/[a-zA-Z]|-?\d*\.?\d+(?:e-?\d+)?/g) || [];
    let i = 0, cx = 0, cy = 0, sx = 0, sy = 0, cmd = 'M';
    const num = () => Number(toks[i++]);
    while (i < toks.length) {
      if (/[a-zA-Z]/.test(toks[i])) cmd = toks[i++];
      const rel = cmd === cmd.toLowerCase(), Cc = cmd.toUpperCase();
      if (Cc === 'Z') { cx = sx; cy = sy; continue; }
      const n = { M: 2, L: 2, T: 2, H: 1, V: 1, Q: 4, S: 4, C: 6, A: 7 }[Cc];
      if (!n) { i++; continue; }
      const v = Array.from({ length: n }, num);
      if (Cc === 'H') cx = rel ? cx + v[0] : v[0];
      else if (Cc === 'V') cy = rel ? cy + v[0] : v[0];
      else if (Cc === 'A') { if (rel) { cx += v[5]; cy += v[6]; } else { cx = v[5]; cy = v[6]; } add(cx - v[0], cy - v[1]); add(cx + v[0], cy + v[1]); }
      else {
        for (let k = 0; k < n; k += 2) add(rel ? cx + v[k] : v[k], rel ? cy + v[k + 1] : v[k + 1]);
        cx = rel ? cx + v[n - 2] : v[n - 2]; cy = rel ? cy + v[n - 1] : v[n - 1];
      }
      add(cx, cy);
      if (Cc === 'M') { sx = cx; sy = cy; cmd = rel ? 'l' : 'L'; }
    }
  }
  return { x: x0, y: y0, w: x1 - x0, h: y1 - y0 };
}
