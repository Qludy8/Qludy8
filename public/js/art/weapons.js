// Armes ORIGINALES (aucune reproduction de modèle réel), dessinées pièce par pièce dans un espace 1000 × 360,
// canon vers la droite. Chaque pièce a un matériau :
//   paint  : pièce peinte par le skin (carcasse, crosse, garde-main, lame…)
//   poly   : polymère noir mat          metal : acier bruni (sous la peinture)    metal2 : acier bruni posé par-dessus
//   steel  : acier poli (biseaux, culasse) wood : bois    brass : laiton    glass : optique
//   hole   : évidement                   wire : pièce filaire (pontet)           line / hi : gravures et reflets
const P = (k, d) => ({ k, d });
const R = (x, y, w, h) => `M${x} ${y}h${w}v${h}h${-w}Z`;
const C = (cx, cy, r) => `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`;
const RR = (x, y, w, h, r) => `M${x + r} ${y}h${w - 2 * r}q${r} 0 ${r} ${r}v${h - 2 * r}q0 ${r} ${-r} ${r}h${-(w - 2 * r)}q${-r} 0 ${-r} ${-r}v${-(h - 2 * r)}q0 ${-r} ${r} ${-r}Z`;
const rep = (n, f) => Array.from({ length: n }, (_, i) => f(i)).join(' ');
// rail à encoches (dessus)
const rail = (x, y, len, h = 10) => R(x, y, len, h) + ' ' + rep(Math.floor(len / 14), (i) => R(x + 4 + i * 14, y - 5, 8, 5));
const vlines = (x, y1, y2, n, step) => rep(n, (i) => `M${x + i * step} ${y1}V${y2}`);
const hlines = (x1, x2, y, n, step) => rep(n, (i) => `M${x1} ${y + i * step}H${x2}`);

